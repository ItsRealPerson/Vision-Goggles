for fname, lang_code in file_mapping.items():
    fpath = os.path.join(lang_dir, fname)
    if not os.path.exists(fpath):
        print(f"Warning: file {fname} not found!")
        continue
    
    with open(fpath, "r", encoding="utf-8") as fp:
        data = json.load(fp)
    
    dict_to_add = translations[lang_code]
    added = 0
    updated = 0
    for k, v in dict_to_add.items():
        if k not in data:
            data[k] = v
            added += 1
        elif data[k] != v:
            data[k] = v
            updated += 1
            
    with open(fpath, "w", encoding="utf-8") as fp:
        json.dump(data, fp, ensure_ascii=False, indent=2)
        fp.write("\n")
        
    print(f"[{fname}] Successfully synchronized: {added} keys added, {updated} updated (Total keys: {len(data)})")

